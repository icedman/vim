#!/usr/bin/env python3
"""Model buffer-snapshot leaf targets on deterministic datasets.

This mirrors snapshot_leaf_build()'s whole-line payload packing.  It reports
structural storage and copy-amplification measurements; it deliberately does
not claim to measure allocator or wall-clock performance.
"""

from __future__ import annotations

import argparse
import math
from dataclasses import dataclass
from pathlib import Path
from typing import cast

TARGETS = (1024, 4096, 16384, 65536)
SIZE_T_BYTES = 8
COLNR_BYTES = 4


@dataclass(frozen=True)
class Measurement:
    lines: int
    text_bytes: int
    table_bytes: int
    leaves: int
    branches: int
    allocations: int
    average_edit_copy: float
    maximum_leaf: int
    minimum_depth: int
    maximum_avl_depth: int


def datasets() -> dict[str, list[int]]:
    mixed_pattern = [40] * 60 + [100] * 25 + [200] * 10 + [500] * 4 + [2000]
    return {
        "100k-short-20": [20] * 100_000,
        "100k-medium-200": [200] * 100_000,
        "100k-source-mixed": mixed_pattern * 1000,
        "1k-lines-1MiB": [1024 * 1024] * 1000,
        "one-line-oversized": [128 * 1024],
    }


def pack(lengths: list[int], target: int) -> list[tuple[int, int]]:
    leaves: list[tuple[int, int]] = []
    payload = 0
    line_count = 0
    for length in lengths:
        needed = length + 1
        if line_count > 0 and payload + needed > target:
            leaves.append((payload, line_count))
            payload = 0
            line_count = 0
        payload += needed
        line_count += 1
    if line_count:
        leaves.append((payload, line_count))
    return leaves


def measure(lengths: list[int], target: int) -> Measurement:
    leaves = pack(lengths, target)
    leaf_count = len(leaves)
    branches = max(0, leaf_count - 1)
    minimum_depth = math.ceil(math.log2(leaf_count)) + 1 if leaf_count > 1 else 1
    # AVL trees have height below 1.4405 * log2(n + 2) - 0.3277.
    maximum_depth = (
        math.floor(1.4405 * math.log2(leaf_count + 2) - 0.3277) + 1
        if leaf_count > 1
        else 1
    )
    weighted_copy = sum(payload * count for payload, count in leaves)
    return Measurement(
        lines=len(lengths),
        text_bytes=sum(length + 1 for length in lengths),
        table_bytes=len(lengths) * (SIZE_T_BYTES + COLNR_BYTES),
        leaves=leaf_count,
        branches=branches,
        allocations=1 + leaf_count + branches,
        average_edit_copy=weighted_copy / len(lengths),
        maximum_leaf=max(payload for payload, _ in leaves),
        minimum_depth=minimum_depth,
        maximum_avl_depth=maximum_depth,
    )


def render() -> str:
    output = [
        "# Buffer snapshot leaf-target structural report",
        "",
        "Generated by `tools/benchmark_buffer_snapshot.py`.",
        "",
        "The model mirrors `snapshot_leaf_build()`: whole lines are packed by",
        "NUL-inclusive text payload, and a single oversized line remains one leaf.",
        "Table bytes assume the configured 64-bit build (`size_t` 8 bytes and",
        "`colnr_T` 4 bytes). Allocation counts include one snapshot handle, one",
        "allocation per leaf, and one per binary branch. Edit-copy bytes are the",
        "mean leaf payload copied when choosing a line uniformly at random.",
        "Release depth is a structural AVL bound, not a latency measurement.",
        "",
    ]
    for name, lengths in datasets().items():
        output.extend(
            [
                f"## {name}",
                "",
                "| Target | Text bytes | Table bytes | Leaves | Branches | Allocations | Mean edit copy | Max leaf | AVL depth |",
                "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
            ]
        )
        for target in TARGETS:
            result = measure(lengths, target)
            output.append(
                "".join(
                    (
                        f"| {target // 1024} KiB | {result.text_bytes} | ",
                        f"{result.table_bytes} | {result.leaves} | ",
                        f"{result.branches} | {result.allocations} | ",
                        f"{result.average_edit_copy:.1f} | {result.maximum_leaf} | ",
                        f"{result.minimum_depth}-{result.maximum_avl_depth} |",
                    )
                )
            )
        output.append("")
    output.extend(
        [
            "## Interpretation",
            "",
            "The 1 KiB target minimizes sparse-edit copying but multiplies branch",
            "and allocation counts. The 16 and 64 KiB targets reduce index overhead",
            "but proportionally retain and copy more unchanged text for sparse edits.",
            "The 4 KiB target remains the balanced default: normal random-edit copy",
            "amplification stays near one small page while tree depth and allocation",
            "counts remain modest. Oversized-line behavior is target-independent.",
            "",
            "Binary AVL fanout remains appropriate for path-copying: the 4 KiB",
            "depth bound is small even for 100,000-line datasets. Final release visits",
            "all reachable nodes, but recursive stack depth follows the displayed AVL",
            "bound rather than node count. Deferred release batching is therefore not",
            "justified by stack depth alone; latency still requires wall-clock and",
            "sanitizer measurements before worker use.",
            "",
        ]
    )
    return "\n".join(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument(
        "--output",
        type=Path,
        default=Path("upgrades/buffer-snapshot/leaf-target-report.md"),
    )
    args = parser.parse_args()
    output = cast(Path, args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    _ = output.write_text(render(), encoding="utf-8")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
