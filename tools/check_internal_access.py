#!/usr/bin/env python3
"""Report direct buffer/memline access in Vim source files.

The report is intended to track the buffer-interface migration described in
UPGRADE.md.  It deliberately reports implementation files too: callers and
memline internals must be distinguished during review, not hidden by the
scanner.
"""

from __future__ import annotations

import argparse
import re
from collections.abc import Iterable
from collections import Counter
from dataclasses import dataclass
from pathlib import Path


SOURCE_SUFFIXES = {
    ".c",
    ".cc",
    ".cpp",
    ".h",
    ".inc",
    ".pro",
}


@dataclass(frozen=True)
class Rule:
    name: str
    pattern: re.Pattern[str]


RULES: tuple[Rule, ...] = (
    Rule("buffer memline member", re.compile(r"(?:->|\.)b_ml\b")),
    Rule(
        "memline cached/locked member",
        re.compile(r"(?:->|\.)ml_(?:line_ptr|locked(?:_low|_high|_lineadd)?|stack)\b"),
    ),
    Rule(
        "implicit current-buffer line access",
        re.compile(
            r"\bml_(?:get|get_len|replace|replace_len|append|append_flags|delete|delete_flags)\s*\("
        ),
    ),
    Rule("BUFEMPTY macro", re.compile(r"\bBUFEMPTY\s*\(")),
    Rule(
        "writable line access",
        re.compile(r"\bml_get_buf\s*\([^\n]*,\s*(?:TRUE|true)\s*\)"),
    ),
)


@dataclass(frozen=True)
class Finding:
    line_number: int
    rule: str
    text: str


@dataclass(frozen=True)
class MutationCandidate:
    access_line_number: int
    mutation_line_number: int
    variable: str
    text: str


LINE_ACCESS = re.compile(
    r"(?P<variable>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*"
    + r"ml_(?:get|get_buf)\s*\("
)
LENGTH_ACCESS = re.compile(
    r"(?P<variable>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*"
    + r"ml_(?:get_len|get_buf_len)\s*\("
)
VARIABLE_MUTATION = re.compile(
    r"(?:\*\s*(?P<variable>[A-Za-z_][A-Za-z0-9_]*)|"
    + r"(?P<indexed>[A-Za-z_][A-Za-z0-9_]*)\s*\[[^\]]+\])\s*=(?!=)"
    + r"|\b(?:STRCPY|STRCAT|mch_memmove|memmove|vim_memset)\s*\(\s*"
    + r"(?P<argument>[A-Za-z_][A-Za-z0-9_]*)\b"
)


def source_files(source_root: Path) -> Iterable[Path]:
    for path in sorted(source_root.rglob("*")):
        if path.is_file() and path.suffix.lower() in SOURCE_SUFFIXES:
            yield path


def findings_for_line(line: str, line_number: int) -> list[Finding]:
    findings: list[Finding] = []
    for rule in RULES:
        if rule.pattern.search(line):
            findings.append(Finding(line_number, rule.name, line.rstrip("\n")))
    return findings


def scan_file(path: Path) -> tuple[list[Finding], list[MutationCandidate]]:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    findings: list[Finding] = []
    accesses: list[tuple[int, str]] = []

    for line_number, line in enumerate(lines, start=1):
        findings.extend(findings_for_line(line, line_number))
        access = LINE_ACCESS.search(line) or LENGTH_ACCESS.search(line)
        if access:
            accesses.append((line_number, access.group("variable")))

    mutations: list[MutationCandidate] = []
    for access_line, variable in accesses:
        # This is deliberately a review inventory, not a C parser. Limit the
        # search to the following 80 lines to avoid crossing unrelated code.
        for line_number in range(access_line, min(access_line + 80, len(lines))):
            match = VARIABLE_MUTATION.search(lines[line_number])
            if not match:
                continue
            if (
                match.group("variable")
                and re.search(
                    rf"^\s*[A-Za-z_][A-Za-z0-9_]*\s+\*\s*"
                    rf"{re.escape(match.group('variable'))}\s*=",
                    lines[line_number],
                )
            ):
                continue
            mutated_variable = (
                match.group("variable")
                or match.group("indexed")
                or match.group("argument")
            )
            if mutated_variable == variable and line_number + 1 != access_line:
                mutations.append(
                    MutationCandidate(
                        access_line, line_number + 1, variable, lines[line_number]
                    )
                )
                break

    return findings, mutations


def write_report(report_path: Path, source_root: Path, repo_root: Path) -> tuple[int, int]:
    scanned_files = 0
    files_with_findings = 0
    total_findings = 0
    rule_totals: Counter[str] = Counter()
    mutation_totals = 0

    with report_path.open("w", encoding="utf-8") as report:
        report.write("Vim internal buffer/memline access report\n")
        report.write(f"Source root: {source_root.relative_to(repo_root)}\n")
        report.write("Generated by: tools/check_internal_access.py\n\n")
        report.write("Rules:\n")
        for rule in RULES:
            report.write(f"  - {rule.name}\n")
        report.write("\n")

        for path in source_files(source_root):
            scanned_files += 1
            findings, mutations = scan_file(path)
            if not findings and not mutations:
                continue

            files_with_findings += 1
            total_findings += len(findings)
            mutation_totals += len(mutations)
            relative_path = path.relative_to(repo_root)
            report.write(f"{relative_path}\n")
            report.write("=" * len(str(relative_path)) + "\n")
            for finding in findings:
                rule_totals[finding.rule] += 1
                report.write(
                    f"{relative_path}:{finding.line_number}: "
                    f"[{finding.rule}] {finding.text}\n"
                )

            if mutations:
                report.write("Mutation follow-up candidates:\n")
                for mutation in mutations:
                    report.write(
                        f"{relative_path}:{mutation.mutation_line_number}: "
                        f"{mutation.variable} from line "
                        f"{mutation.access_line_number} is mutated: "
                        f"{mutation.text}\n"
                    )
                report.write("\n")

            file_totals = Counter(finding.rule for finding in findings)
            report.write(
                f"Stats: {len(findings)} access finding(s); "
                f"{len(mutations)} mutation follow-up candidate(s)"
            )
            for rule in RULES:
                if file_totals[rule.name]:
                    report.write(f"; {rule.name}={file_totals[rule.name]}")
            report.write("\n\n")

        report.write("Totals\n")
        report.write("======\n")
        report.write(f"Source files scanned: {scanned_files}\n")
        report.write(f"Files with findings: {files_with_findings}\n")
        report.write(f"Total access findings: {total_findings}\n")
        report.write(f"Mutation follow-up candidates: {mutation_totals}\n")
        for rule in RULES:
            report.write(f"{rule.name}: {rule_totals[rule.name]}\n")

    return scanned_files, total_findings


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Scan Vim source files for direct buffer/memline access."
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="repository root (default: inferred from this script's location)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="report path (default: <root>/internal_access.txt)",
    )
    args = parser.parse_args()

    repo_root = (args.root or Path(__file__).resolve().parents[1]).resolve()
    source_root = repo_root / "src"
    report_path = (args.output or repo_root / "internal_access.txt").resolve()

    if not source_root.is_dir():
        _ = parser.error(f"source directory does not exist: {source_root}")
    if report_path.parent != repo_root:
        _ = report_path.parent.mkdir(parents=True, exist_ok=True)

    scanned_files, total_findings = write_report(report_path, source_root, repo_root)
    print(
        (
            f"Scanned {scanned_files} source files; "
            f"found {total_findings} internal access occurrence(s)."
        )
    )
    print(f"Report written to {report_path.relative_to(repo_root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
